print("Anna kolme kokonaislukua: ")
luku_yksi = int(input("Ensimmäinen luku: "))
luku_kaksi = int(input("Toinen luku: "))
luku_kolme = int(input("Kolmas luku: "))

lukujen_summa = luku_yksi + luku_kaksi + luku_kolme
lukujen_tulo = luku_yksi * luku_kaksi * luku_kolme
lukujen_keskiarvo = lukujen_summa / 3

print("")
print("Lukujen summa on: ", lukujen_summa)
print("Lukujen tulo on: ", lukujen_tulo)
print("Lukujen keskiarvo on: ", lukujen_keskiarvo)