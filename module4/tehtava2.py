hyttiluokka = str(input("Anna hyttiluokka: "))

if hyttiluokka == "LUX": #or "Lux" or "lux":
    print("Hyttiluokkasi on LUX.")

elif hyttiluokka == "A": #or "a":
    print("Hyttiluokkasi on A.")

elif hyttiluokka == "B": #or "b":
    print("Hyttiluokkasi on B.")

elif hyttiluokka == "C": #or "c":
    print("Hyttiluokkasi on C.")
    
else:
    print("Virheellinen hyttiluokka.")